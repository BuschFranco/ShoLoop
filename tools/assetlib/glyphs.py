# --- Accents ---------------------------------------------------------------------------------
#
# Placed into rows the base letter leaves empty: rows 0-1 for lowercase (x-height starts at row 2),
# and negative rows for uppercase, which fills its whole 7-row block. Negative rows are legal here —
# they simply render above the cap line, and the font's ascender is set to make room.

ACUTE_LOWER = {0: "...#.", 1: "..#.."}
ACUTE_UPPER = {-2: "...#.", -1: "..#.."}
TILDE_LOWER = {0: ".###.", 1: "#...#"}
TILDE_UPPER = {-2: ".###.", -1: "#...#"}

# accented char -> (base char, mark)
ACCENTED = {
    "á": ("a", ACUTE_LOWER), "é": ("e", ACUTE_LOWER), "í": ("i", ACUTE_LOWER),
    "ó": ("o", ACUTE_LOWER), "ú": ("u", ACUTE_LOWER), "ñ": ("n", TILDE_LOWER),
    "Á": ("A", ACUTE_UPPER), "É": ("E", ACUTE_UPPER), "Í": ("I", ACUTE_UPPER),
    "Ó": ("O", ACUTE_UPPER), "Ú": ("U", ACUTE_UPPER), "Ñ": ("N", TILDE_UPPER),
}


def build_glyph_table():
    """char -> {row_index: "#####"}, with row 0 the top of the 7-row block and 6 on the baseline.

    Accented letters are assembled here rather than stored, so a change to the acute mark moves every
    á é í ó ú at once.
    """
    table = {}
    for source in (DIGITS, UPPER, LOWER, PUNCT, SYMBOLS):
        for char, rows in source.items():
            table[char] = {i: row for i, row in enumerate(rows)}

    for char, (base, mark) in ACCENTED.items():
        if base not in table:
            raise KeyError(f"accented '{char}' needs base '{base}', which isn't defined")
        # The dotless variants matter: 'í' keeps the i's own dot *and* an accent otherwise, which
        # reads as a smudge at 5px wide. Row 0 is where the i's dot lives, and the mark overwrites it.
        composed = dict(table[base])
        composed.update(mark)
        table[char] = composed

    return table
