"""The pixel shapes of every character the game renders.

Each glyph is 7 rows of 5 columns, '#' on and '.' off, drawn top-down with the last row sitting on
the baseline. Two things escape that box:

- **Descenders** (g j p q y and the comma) carry `descent=1`, which shifts the whole block down a row
  so its bottom lands below the baseline.
- **Accents** are composed, not drawn. `á` is `a` plus an acute mark placed in the rows the lowercase
  letter leaves empty; `Á` is `A` plus the same mark pushed above the cap. Composing them means the
  accents can't drift apart from each other, and it turns ~13 hand-drawn accented glyphs into two
  marks and a table.

WHY THIS FILE EXISTS AT ALL
---------------------------
The UI is Spanish and uses 25 non-ASCII codepoints. Thirteen are ordinary Spanish (áéíóú ñ ÁÉÍÓÚ ¡¿),
but nine are symbols almost no free pixel font ships: ─ (the "── COMBATE ──" separators in the pause
menu), ★ ("★ MEJOR" on reward cards), ◀ ▶ (the pilot carousel arrows), ✓ ✗ (builds and loadout), →
(build requirement rows), and · × − — scattered through the HUD. Drawing them ourselves is what makes
missing-glyph boxes impossible rather than something to discover on screen later.
"""

